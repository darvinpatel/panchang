const GU_DIGITS = "૦૧૨૩૪૫૬૭૮૯";

export function guDigits(value: number | string): string {
  return String(value).replace(/\d/g, (digit) => GU_DIGITS[Number(digit)] ?? digit);
}

export function rashiIndex(longitude: number): number {
  return Math.floor(wrap360(longitude) / 30) % 12;
}

export function wrap360(deg: number): number {
  const value = deg % 360;
  return value < 0 ? value + 360 : value;
}

export function tithiName(paksha: "shukla" | "krishna", tithi: number): { en: string; gu: string } {
  if (tithi === 15 && paksha === "shukla") return { en: "Purnima", gu: "પૂનમ" };
  if (tithi === 15 && paksha === "krishna") return { en: "Amavasya", gu: "અમાસ" };
  return { en: TITHI_EN[tithi] ?? "Tithi", gu: TITHI_GU[tithi] ?? "" };
}

export function karanaAt(elongation: number): { en: string; gu: string; index: number } {
  let half = Math.floor(wrap360(elongation) / 6);
  if (half >= 60) half = 0;
  let nameIndex = 0;
  if (half === 0) nameIndex = 0;
  else if (half >= 57) nameIndex = 8 + (half - 57);
  else nameIndex = 1 + ((half - 1) % 7);
  return { en: KARANAS[nameIndex], gu: KARANAS_GU[nameIndex], index: half };
}

